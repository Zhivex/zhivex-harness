import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { workspaceFixture } from './workspace-fixture.js';
const app = await workspaceFixture();
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(app.url);
  await page.getByRole('button', { name: 'Proyectos', exact: true }).click();
  await page.getByRole('button', { name: 'Abrir carpeta' }).click();
  await page.getByRole('heading', { name: 'sample-project', exact: true }).waitFor();
  await page.getByRole('button', { name: 'README.md', exact: true }).click();
  await page.getByRole('button', { name: 'Adjuntar estas líneas' }).click();
  await page.getByLabel('Mensaje para el agente').fill('Inspect this project');
  await page.getByRole('button', { name: 'Enviar', exact: true }).click();
  await page.getByRole('button', { name: 'Inspect this project', exact: false }).waitFor();
  await page.getByRole('button', { name: '+ Nueva conversación' }).click();
  await page.getByLabel('Mensaje para el agente').fill('Unsent draft');
  await page.getByRole('button', { name: 'Inspect this project', exact: false }).click();
  await page.getByText('Workspace ready.', { exact: false }).waitFor();
  await page.locator('.workspace-run-status').getByText('Completada', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'README.md', exact: true }).first().click();
  await page.getByText('Líneas 2–4 de 4').waitFor();
  await page.screenshot({ path: '/tmp/tauri-stage2/workspace-desktop.png', fullPage: true });
  await page.reload();
  await page.getByRole('button', { name: 'Proyectos', exact: true }).click();
  await page.getByText('Workspace ready.', { exact: false }).waitFor();
  assert.equal(await page.locator('.workspace-response').count(), 1);
  assert.equal(await page.locator('.workspace-tool-list code').count(), 1);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction((element: any) => element.getBoundingClientRect().right <= 0, await page.locator('.sidebar').elementHandle());
  await page.screenshot({ path: '/tmp/tauri-stage2/workspace-mobile.png', fullPage: true });
  assert.equal(await page.evaluate('document.documentElement.scrollWidth > innerWidth'), false);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByLabel('Mensaje para el agente').fill('Cancel this follow-up');
  await page.getByRole('button', { name: 'Enviar', exact: true }).click();
  await page.getByRole('button', { name: 'Detener', exact: true }).click();
  await page.getByText('Detenida', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log('Workspace browser smoke passed: project selection, file context, tool activity, navigation during execution, file links, replay and mobile layout.');
} finally { await browser.close(); await app.close(); }
