import {readFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';

const desktop = path.resolve(import.meta.dir, '..');
const installed = JSON.parse(await readFile(path.join(desktop, '.harness/installed.json'), 'utf8'));
const packageRoot = path.join(installed.install, 'node_modules/@zhivex-ai/harness');
const manifest = JSON.parse(await readFile(path.join(packageRoot, 'package.json'), 'utf8'));
const entry = manifest.exports['./application/protocol'];
assert(entry?.import && entry?.types);
const result = await Bun.build({entrypoints: [path.resolve(packageRoot, entry.import)], target: 'browser'});
assert(result.success, String(result.logs));
const output = await result.outputs[0]!.text();
assert(!/node:|process\.|Buffer|require\(|connectCoordinator|createHarness|@zhivex-ai\/agents/.test(output));
const exports = JSON.parse(execFileSync('node', ['--input-type=module', '-e', 'const module = await import(process.argv[1]); console.log(JSON.stringify(module));', 'data:text/javascript,' + encodeURIComponent(output)], {encoding: 'utf8'}));
assert.deepEqual(exports, {APPLICATION_PROJECTION_VERSION: 1});
const declaration = await readFile(path.resolve(packageRoot, entry.types), 'utf8');
assert(declaration.includes('../application/contracts.js'));
const contracts = await readFile(path.join(packageRoot, 'dist/application/contracts.d.ts'), 'utf8');
assert(!/\bimport\b|\bfrom\s+['"]/.test(contracts), 'Projection declarations must be standalone');
console.log(JSON.stringify({passed: true, coreArtifactSha256: installed.sha256, checks: ['installed browser bundle has no host or Node imports', 'browser bundle exports only the projection version', 'installed declarations refer only to standalone contracts']}, null, 2));
