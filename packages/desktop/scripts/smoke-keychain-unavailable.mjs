import {mkdtemp, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {_electron as electron} from 'playwright';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const installed = JSON.parse(await readFile(path.join(root, 'packages/desktop/.harness/installed.json'), 'utf8'));
const {startApplicationCoordinator} = await import(path.join(installed.install, 'node_modules/@zhivex-ai/harness/dist/engine/application.js'));
const {connectCoordinator} = await import(path.join(installed.install, 'node_modules/@zhivex-ai/harness/dist/engine/application-client.js'));
const directory = await mkdtemp('/tmp/zhx-keychain-ui-');
let finish, reads = 0, writes = 0, desktop;
const started = Date.now();
const owner = await startApplicationCoordinator(directory + '/app', {secrets: {read() {reads++; return reads === 1 ? new Promise(resolve => {finish = resolve;}) : Promise.resolve(null);}, async write() {writes++;}}});
const startupMs = Date.now() - started;
assert(startupMs < 15000);
try {
  const coordinator = await connectCoordinator(directory + '/app');
  desktop = await electron.launch({executablePath: path.join(root, 'packages/desktop/out/Zhivex Harness-darwin-arm64/Zhivex Harness.app/Contents/MacOS/Zhivex Harness'), args: ['--assistant-directory', directory + '/app', '--user-data', directory + '/electron'], env: {PATH: '/usr/bin:/bin', HOME: process.env.HOME}, timeout: 45000});
  const page = await desktop.firstWindow(); await page.waitForSelector('.unified-shell');
  const metadata = await desktop.evaluate(({app}) => JSON.parse(process.getBuiltinModule('node:fs').readFileSync(app.getAppPath() + '/build/runtime-metadata.json', 'utf8')));
  assert.equal(metadata.harnessArtifactSha256, installed.sha256);
  await page.getByText('Your saved assistants are temporarily unavailable.', {exact: false}).waitFor();
  assert.equal(await page.getByRole('button', {name: 'Create assistant', exact: true}).count(), 0);
  assert.equal((await coordinator.state()).state.locked, true);
  await page.getByRole('button', {name: 'Retry startup', exact: true}).click();
  await page.getByRole('alert').filter({hasText: 'The system keychain is still responding.'}).waitFor();
  assert.equal(reads, 1); assert.equal(writes, 0);
  await page.screenshot({path: path.join(directory, 'locked.png')});
  finish(null); await Promise.resolve(); await Promise.resolve();
  assert.equal((await coordinator.state()).state.locked, true);
  await page.getByRole('button', {name: 'Retry startup', exact: true}).click();
  await page.getByRole('button', {name: 'Create assistant', exact: true}).waitFor();
  assert.equal((await coordinator.state()).state.locked, false);
  assert.equal(reads, 2); assert.equal(writes, 0);
  await page.screenshot({path: path.join(directory, 'recovered.png')});
  await desktop.close(); desktop = undefined;
  const report = {passed: true, directory, coreArtifactSha256: installed.sha256, startupMs, checks: ['bounded read exposes locked state', 'no empty profile creation form while locked', 'pending read retry does not overlap', 'late read does not unlock silently', 'explicit retry unlocks after reread', 'zero credential writes'], limitations: 'Installed core and packaged Electron with a deliberately unresolved SecretStore read. No native Keychain permissions changed or cross-identity access certified. Native read cancellation and native worker lifetime remain separate concerns.'};
  await writeFile(path.join(directory, 'report.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report, null, 2));
} finally {
  const timer = setTimeout(() => desktop?.process().kill('SIGKILL'), 15000);
  await desktop?.close().catch(() => {}); clearTimeout(timer); await owner.close();
}
